// RootHelpText renders clap's page for the root command: `-h` prints the short
// layout and `--help` / `help` print the long one.
func RootHelpText(short bool) string {
	return SubcommandHelpText(&SubcommandHelpRequest{Short: short})
}

// SubcommandHelpRequest mirrors clap's help action for a subcommand path.
type SubcommandHelpRequest struct {
	// Path is the space-separated command path whose page clap prints.
	Path string
	// Short selects clap's `-h` summary layout instead of `--help`.
	Short bool
	// UnexpectedValue is set for `--help=<value>`: clap rejects the value
	// instead of printing the page.
	UnexpectedValue *string
}

// SubcommandHelpText renders the captured page for a request.
func SubcommandHelpText(request *SubcommandHelpRequest) string {
	if request == nil {
		return ""
	}
	pages := subcommandHelpPages
	if request.Short {
		pages = subcommandShortHelpPages
	}
	lines, ok := pages[request.Path]
	if !ok {
		return ""
	}
	return strings.Join(lines, "\n") + "\n"
}

// subcommandFlagTakesValue reports whether the token is a flag of the command
// at path and whether that flag consumes the token after it. `--flag=value` and
// attached short forms (`-cvalue`) carry their value inline and therefore
// consume nothing.
func subcommandFlagTakesValue(path, token string) (takesValue bool, known bool) {
	table, ok := subcommandFlagSpecs[path]
	if !ok {
		return false, false
	}
	name, _, hasInlineValue := strings.Cut(token, "=")
	if takes, ok := table[name]; ok {
		return takes && !hasInlineValue, true
	}
	if len(name) > 2 && strings.HasPrefix(name, "-") && !strings.HasPrefix(name, "--") {
		if _, ok := table[name[:2]]; ok {
			// clap treats the rest of the token as the attached value, so the
			// flag consumes nothing further.
			return false, true
		}
	}
	return false, false
}

// SubcommandHelpRequestFor resolves clap's help action for a subcommand path.
// clap parses left to right, so an unknown flag or `--` before the help flag
// keeps the diagnostic the command's own parser produces.
func SubcommandHelpRequestFor(command string, args []string) *SubcommandHelpRequest {
	if command == "" {
		return nil
	}
	path := command
	rest := args
	for len(rest) > 0 {
		candidate := path + " " + rest[0]
		if _, ok := subcommandHelpPages[candidate]; !ok {
			break
		}
		path = candidate
		rest = rest[1:]
	}
	if _, ok := subcommandHelpPages[path]; !ok {
		return nil
	}
	if len(rest) >= 2 && rest[0] == "help" {
		topic := path + " " + rest[1]
		if _, ok := subcommandHelpPages[topic]; ok {
			return &SubcommandHelpRequest{Path: topic}
		}
	}
	for i := 0; i < len(rest); i++ {
		token := rest[i]
		switch {
		case token == "--":
			return nil
		case token == "-h":
			return &SubcommandHelpRequest{Path: path, Short: true}
		case token == "--help":
			return &SubcommandHelpRequest{Path: path}
		case strings.HasPrefix(token, "--help="):
			value := strings.TrimPrefix(token, "--help=")
			return &SubcommandHelpRequest{Path: path, UnexpectedValue: &value}
		case len(token) > 2 && strings.HasPrefix(token, "-h") && !strings.HasPrefix(token, "--"):
			// clap fires the help action on the first character of a short
			// cluster, so `-hx` prints the `-h` layout. Commands whose
			// positionals accept hyphen values bind the token as a value.
			if !subcommandAttachedShortHelp[path] {
				return nil
			}
			return &SubcommandHelpRequest{Path: path, Short: true}
		case len(token) > 1 && strings.HasPrefix(token, "-"):
			takesValue, known := subcommandFlagTakesValue(path, token)
			if !known {
				return nil
			}
			if takesValue {
				i++
			}
		}
	}
	return nil
}
